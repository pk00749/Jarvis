    def call(self, params: Union[str, dict], **kwargs) -> str:
        if isinstance(params, str):
            params = json.loads(params) if params.startswith('{') else {'category': params}
        
        category = params.get('category', '') if isinstance(params, dict) else params
        
        if not category:
            all_jokes = [joke for category_jokes in self.jokes.values() for joke in category_jokes]
            return random.choice(all_jokes)
        
        if category not in self.jokes:
            available = '、'.join(self.jokes.keys())
            return f"我有{available}种笑话，你想听哪种呀？"
        
        jokes_list = self.jokes[category]
        return random.choice(jokes_list)
